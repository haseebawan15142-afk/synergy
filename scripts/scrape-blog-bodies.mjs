/**
 * Fetches legacy blog HTML and writes src/lib/content/blog-bodies.generated.ts
 * Run: node scripts/scrape-blog-bodies.mjs [--limit=N] [--slug=xxx]
 */
import { readFileSync, writeFileSync, existsSync } from "fs";
import { join } from "path";
import { fileURLToPath } from "url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const metaPath = join(root, "src", "lib", "content", "blog-posts.generated.ts");
const outPath = join(root, "src", "lib", "content", "blog-bodies.generated.ts");

const limitArg = process.argv.find((a) => a.startsWith("--limit="));
const slugArg = process.argv.find((a) => a.startsWith("--slug="));
const limit = limitArg ? Number(limitArg.split("=")[1]) : undefined;
const onlySlug = slugArg ? slugArg.split("=")[1] : undefined;

if (!existsSync(metaPath)) {
  console.error("[scrape-blogs] Run sync-blogs-from-legacy.mjs first");
  process.exit(1);
}

const metaSrc = readFileSync(metaPath, "utf8");
const jsonMatch = metaSrc.match(/export const blogPostsGenerated[^=]*=\s*(\[[\s\S]*\]);/);
if (!jsonMatch) {
  console.error("[scrape-blogs] Could not parse blog-posts.generated.ts");
  process.exit(1);
}
const posts = JSON.parse(jsonMatch[1]);

function extractBody(html) {
  const startMarkers = [
    /<div class="blog-details[\s\S]*?<div class="[^"]*blog-content[^"]*">/i,
    /<section class="blog[\s\S]*?>/i,
    /<div class="container[\s\S]*?<h1[^>]*>/i,
  ];
  let chunk = html;
  for (const re of startMarkers) {
    const m = html.match(re);
    if (m) {
      chunk = html.slice(m.index ?? 0);
      break;
    }
  }

  const endIdx = chunk.search(/Contact US!|How can we help\?|<footer/i);
  const slice = endIdx > 0 ? chunk.slice(0, endIdx) : chunk.slice(0, 120000);

  const blocks = [];
  const pRe = /<p[^>]*>([\s\S]*?)<\/p>/gi;
  let pm;
  while ((pm = pRe.exec(slice)) !== null) {
    const text = pm[1]
      .replace(/<[^>]+>/g, " ")
      .replace(/&nbsp;/g, " ")
      .replace(/&#\d+;/g, " ")
      .replace(/\s+/g, " ")
      .trim();
    if (text.length > 40) blocks.push(text);
  }

  const hRe = /<h[23][^>]*>([\s\S]*?)<\/h[23]>/gi;
  let hm;
  while ((hm = hRe.exec(slice)) !== null) {
    const text = hm[1].replace(/<[^>]+>/g, "").trim();
    if (text.length > 3 && !/^Contact/i.test(text)) blocks.unshift(`## ${text}`);
  }

  return blocks.length ? blocks : null;
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

let list = posts;
if (onlySlug) list = list.filter((p) => p.slug === onlySlug);
if (limit) list = list.slice(0, limit);

const existing = existsSync(outPath)
  ? JSON.parse(
      readFileSync(outPath, "utf8")
        .replace(/^[\s\S]*?\{/, "{")
        .replace(/\};\s*$/, "}"),
    )
  : {};

const bodies = { ...existing };
let ok = 0;
let fail = 0;

for (const post of list) {
  if (bodies[post.slug]?.length) {
    continue;
  }
  try {
    const res = await fetch(post.legacyUrl, {
      headers: { "User-Agent": "SynergyWebsiteMigration/1.0" },
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const html = await res.text();
    const body = extractBody(html);
    if (body) {
      bodies[post.slug] = body;
      ok++;
      process.stdout.write(`.\n${post.slug}\n`);
    } else {
      fail++;
      console.warn(`[skip] no body: ${post.slug}`);
    }
  } catch (e) {
    fail++;
    console.warn(`[fail] ${post.slug}: ${e.message}`);
  }
  await sleep(350);
}

const ts = `/* Auto-generated by scripts/scrape-blog-bodies.mjs — ${Object.keys(bodies).length} entries */
export const blogBodiesGenerated: Record<string, string[]> = ${JSON.stringify(bodies, null, 2)};
`;

writeFileSync(outPath, ts, "utf8");
console.log(`[scrape-blogs] done ok=${ok} fail=${fail} total=${Object.keys(bodies).length}`);
