/**
 * Keeps hero slides in sync with images in public/images/hero
 * and writes src/lib/content/hero-slides.generated.ts
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "fs";
import { join, extname } from "path";
import { fileURLToPath } from "url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const destDir = join(root, "public", "images", "hero");
const outFile = join(root, "src", "lib", "content", "hero-slides.generated.ts");

function slug(name) {
  return name
    .replace(extname(name), "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

mkdirSync(destDir, { recursive: true });

let slides = [];

if (existsSync(destDir)) {
  const files = readdirSync(destDir)
    .filter((f) => /\.(jpe?g|webp|png)$/i.test(f))
    .sort((a, b) => a.localeCompare(b));

  for (const file of files) {
    slides.push({
      src: `/images/hero/${file}`,
      alt: file.replace(extname(file), "").replace(/[-_]/g, " "),
    });
  }
}

if (slides.length === 0) {
  slides = [{ src: "/images/hero/enterprise-image.jpg", alt: "Enterprise technology" }];
}

const ts = `/* Auto-generated by scripts/sync-hero-images.mjs — do not edit */
export const heroSlidesGenerated = ${JSON.stringify(slides, null, 2)} as const;
`;

writeFileSync(outFile, ts, "utf8");
console.log(`[sync-hero-images] ${slides.length} slide(s) → hero-slides.generated.ts`);
